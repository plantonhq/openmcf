package module

import (
	"github.com/pkg/errors"
	"github.com/pulumi/pulumi-gcp/sdk/v9/go/gcp"
	"github.com/pulumi/pulumi-gcp/sdk/v9/go/gcp/identityplatform"
	"github.com/pulumi/pulumi-gcp/sdk/v9/go/gcp/projects"
	"github.com/pulumi/pulumi/sdk/v3/go/pulumi"
)

// identityPlatformTenant provisions the Identity Platform tenant plus its
// composed tenant-scoped identity-provider configs.
//
// The project's Identity Platform must already be initialized with
// multi_tenant.allow_tenants enabled (the GcpIdentityPlatformConfig kind)
// — the tenant API rejects creation otherwise. The tenant's resource ID is
// generated by GCP at create time and flows to the IdP configs through the
// created resource's Name output, never from the spec.
//
// The spec's ONE deletion_policy fans out to the tenant AND every composed
// IdP config — the IdP configs have no life apart from the tenant, so one
// switch governs all of them.
func identityPlatformTenant(ctx *pulumi.Context, locals *Locals, gcpProvider *gcp.Provider) error {
	spec := locals.GcpIdentityPlatformTenant.Spec

	// Enable the Identity Toolkit API — a no-op on projects the config
	// kind already initialized, and what makes this kind self-sufficient
	// on projects configured outside Planton. disable_on_destroy stays
	// false: tearing down one tenant must never disable authentication
	// for everything else in the project. Matches the Terraform module.
	serviceArgs := &projects.ServiceArgs{
		Service:                  pulumi.String("identitytoolkit.googleapis.com"),
		DisableDependentServices: pulumi.BoolPtr(true),
	}
	if spec.ProjectId.GetValue() != "" {
		serviceArgs.Project = pulumi.String(spec.ProjectId.GetValue())
	}
	createdProjectService, err := projects.NewService(ctx,
		"tenant-identitytoolkit.googleapis.com", serviceArgs, pulumi.Provider(gcpProvider))
	if err != nil {
		return errors.Wrap(err, "failed to enable identitytoolkit.googleapis.com api")
	}

	args := &identityplatform.TenantArgs{
		DisplayName: pulumi.String(spec.DisplayName),
	}
	if spec.AllowPasswordSignup {
		args.AllowPasswordSignup = pulumi.BoolPtr(true)
	}
	if spec.EnableEmailLinkSignin {
		args.EnableEmailLinkSignin = pulumi.BoolPtr(true)
	}
	if spec.DisableAuth {
		args.DisableAuth = pulumi.BoolPtr(true)
	}
	if spec.ClientPermissions != nil {
		args.Client = &identityplatform.TenantClientArgs{
			Permissions: &identityplatform.TenantClientPermissionsArgs{
				DisabledUserSignup:   pulumi.BoolPtr(spec.ClientPermissions.DisabledUserSignup),
				DisabledUserDeletion: pulumi.BoolPtr(spec.ClientPermissions.DisabledUserDeletion),
			},
		}
	}
	if spec.DeletionPolicy != "" {
		args.DeletionPolicy = pulumi.StringPtr(spec.DeletionPolicy)
	}
	if spec.ProjectId.GetValue() != "" {
		args.Project = pulumi.String(spec.ProjectId.GetValue())
	}

	createdTenant, err := identityplatform.NewTenant(ctx, "tenant", args,
		pulumi.Provider(gcpProvider), pulumi.DependsOn([]pulumi.Resource{createdProjectService}))
	if err != nil {
		return errors.Wrap(err, "failed to create identity platform tenant")
	}

	// Name is the server-generated tenant ID; ID() is the full
	// projects/{project}/tenants/{tenant_id} path.
	ctx.Export(OpTenantId, createdTenant.Name)
	ctx.Export(OpTenantName, createdTenant.ID().ToStringOutput())

	for _, idp := range spec.DefaultSupportedIdps {
		idpArgs := &identityplatform.TenantDefaultSupportedIdpConfigArgs{
			Tenant:       createdTenant.Name,
			IdpId:        pulumi.String(idp.IdpId),
			ClientId:     pulumi.String(idp.ClientId),
			ClientSecret: pulumi.String(idp.ClientSecret),
			// Explicit send — a disabled IdP must reach the API.
			Enabled: pulumi.Bool(idp.Enabled == nil || idp.GetEnabled()),
		}
		if spec.DeletionPolicy != "" {
			idpArgs.DeletionPolicy = pulumi.StringPtr(spec.DeletionPolicy)
		}
		if spec.ProjectId.GetValue() != "" {
			idpArgs.Project = pulumi.String(spec.ProjectId.GetValue())
		}
		if _, err := identityplatform.NewTenantDefaultSupportedIdpConfig(ctx,
			"default-idp-"+idp.IdpId, idpArgs, pulumi.Provider(gcpProvider)); err != nil {
			return errors.Wrapf(err, "failed to create tenant default supported idp config %s", idp.IdpId)
		}
	}

	for _, oidc := range spec.OauthIdpConfigs {
		oidcArgs := &identityplatform.TenantOauthIdpConfigArgs{
			Tenant:      createdTenant.Name,
			Name:        pulumi.String(oidc.Name),
			DisplayName: pulumi.String(oidc.DisplayName),
			Issuer:      pulumi.String(oidc.Issuer),
			ClientId:    pulumi.String(oidc.ClientId),
			// Explicit send — a disabled IdP must reach the API.
			Enabled: pulumi.Bool(oidc.Enabled == nil || oidc.GetEnabled()),
		}
		if oidc.ClientSecret != "" {
			oidcArgs.ClientSecret = pulumi.StringPtr(oidc.ClientSecret)
		}
		if spec.DeletionPolicy != "" {
			oidcArgs.DeletionPolicy = pulumi.StringPtr(spec.DeletionPolicy)
		}
		if spec.ProjectId.GetValue() != "" {
			oidcArgs.Project = pulumi.String(spec.ProjectId.GetValue())
		}
		if _, err := identityplatform.NewTenantOauthIdpConfig(ctx,
			"oauth-idp-"+oidc.Name, oidcArgs, pulumi.Provider(gcpProvider)); err != nil {
			return errors.Wrapf(err, "failed to create tenant oauth idp config %s", oidc.Name)
		}
	}

	for _, saml := range spec.InboundSamlConfigs {
		idpCertificates := identityplatform.TenantInboundSamlConfigIdpConfigIdpCertificateArray{}
		for _, certificate := range saml.IdpConfig.IdpCertificates {
			idpCertificates = append(idpCertificates, &identityplatform.TenantInboundSamlConfigIdpConfigIdpCertificateArgs{
				X509Certificate: pulumi.StringPtr(certificate.X509Certificate),
			})
		}
		samlArgs := &identityplatform.TenantInboundSamlConfigArgs{
			Tenant:      createdTenant.Name,
			Name:        pulumi.String(saml.Name),
			DisplayName: pulumi.String(saml.DisplayName),
			// Explicit send — a disabled IdP must reach the API.
			Enabled: pulumi.Bool(saml.Enabled == nil || saml.GetEnabled()),
			IdpConfig: &identityplatform.TenantInboundSamlConfigIdpConfigArgs{
				IdpEntityId:     pulumi.String(saml.IdpConfig.IdpEntityId),
				SsoUrl:          pulumi.String(saml.IdpConfig.SsoUrl),
				SignRequest:     pulumi.BoolPtr(saml.IdpConfig.SignRequest),
				IdpCertificates: idpCertificates,
			},
			// Required at tenant level — the API's own rule, enforced by
			// the spec's CEL before the module ever runs.
			SpConfig: &identityplatform.TenantInboundSamlConfigSpConfigArgs{
				CallbackUri: pulumi.String(saml.SpConfig.CallbackUri),
				SpEntityId:  pulumi.String(saml.SpConfig.SpEntityId),
			},
		}
		if spec.DeletionPolicy != "" {
			samlArgs.DeletionPolicy = pulumi.StringPtr(spec.DeletionPolicy)
		}
		if spec.ProjectId.GetValue() != "" {
			samlArgs.Project = pulumi.String(spec.ProjectId.GetValue())
		}
		if _, err := identityplatform.NewTenantInboundSamlConfig(ctx,
			"saml-idp-"+saml.Name, samlArgs, pulumi.Provider(gcpProvider)); err != nil {
			return errors.Wrapf(err, "failed to create tenant inbound saml config %s", saml.Name)
		}
	}

	return nil
}
