package module

import (
	"strconv"

	"github.com/pkg/errors"
	kubernetesharborv1alpha1 "github.com/plantonhq/planton/apis/dev/planton/provider/kubernetes/kubernetesharbor/v1alpha1"
	"github.com/pulumi/pulumi/sdk/v3/go/pulumi"
	"sigs.k8s.io/yaml"
)

// buildHelmValues renders the typed spec into the chart's values. The
// Terraform twin (locals.tf `helm_values`) renders the byte-identical
// document — keep them in lockstep.
//
// SECRET DISCIPLINE: every credential travels by Secret NAME through
// the chart's existingSecret sites — with two chart-forced exceptions
// that ride the values as SECRET-marked entries (redacted in
// previews/plans): the internal database superuser password
// (`database.internal.password` — the chart's only intake) and Trivy's
// optional gitHubToken.
func buildHelmValues(locals *Locals, gen *generatedCredentials) (map[string]interface{}, error) {
	spec := locals.Spec

	values := map[string]interface{}{
		// Resource naming is the module's identity contract: every
		// chart-derived name hangs off metadata.name (re-pinned after
		// the helm_values merge below).
		"fullnameOverride": locals.ReleaseName,
		"externalURL":      spec.GetExternalUrl(),
		"logLevel":         "info",
	}
	if spec.GetLogLevel() != "" {
		values["logLevel"] = spec.GetLogLevel()
	}

	// ------------------------------ expose --------------------------------
	// Only clusterIP / nodePort / loadBalancer render (never ingress or
	// route — exposure composes from the catalog's exposure kinds). The
	// active arm's Service NAME is pinned to metadata.name: the chart
	// default is the literal "harbor", which would collide between two
	// installs in one namespace.
	tlsBlock := map[string]interface{}{
		"enabled": spec.GetExpose().GetTls().GetEnabled(),
	}
	if spec.GetExpose().GetTls().GetEnabled() {
		if certSecret := spec.GetExpose().GetTls().GetCertSecretName().GetValue(); certSecret != "" {
			tlsBlock["certSource"] = "secret"
			tlsBlock["secret"] = map[string]interface{}{"secretName": certSecret}
		} else {
			// Chart-generated self-signed cert — regenerated on EVERY
			// apply (helm genCA carries no state); documented as a
			// labs-only posture on the spec field.
			tlsBlock["certSource"] = "auto"
			tlsBlock["auto"] = map[string]interface{}{"commonName": locals.ReleaseName}
		}
	}

	exposeBlock := map[string]interface{}{
		"type": locals.ExposeType,
		"tls":  tlsBlock,
	}
	activeArm := map[string]interface{}{
		"name": locals.ReleaseName,
	}
	if len(spec.GetExpose().GetServiceAnnotations()) > 0 {
		activeArm["annotations"] = stringMapToInterface(spec.GetExpose().GetServiceAnnotations())
	}
	switch locals.ExposeType {
	case "clusterIP":
		exposeBlock["clusterIP"] = activeArm
	case "nodePort":
		ports := map[string]interface{}{}
		if spec.GetExpose().GetNodePorts().GetHttp() != 0 {
			ports["http"] = map[string]interface{}{"nodePort": spec.GetExpose().GetNodePorts().GetHttp()}
		}
		if spec.GetExpose().GetNodePorts().GetHttps() != 0 {
			ports["https"] = map[string]interface{}{"nodePort": spec.GetExpose().GetNodePorts().GetHttps()}
		}
		if len(ports) > 0 {
			activeArm["ports"] = ports
		}
		exposeBlock["nodePort"] = activeArm
	case "loadBalancer":
		if spec.GetExpose().GetLoadBalancerIp() != "" {
			activeArm["IP"] = spec.GetExpose().GetLoadBalancerIp()
		}
		if len(spec.GetExpose().GetSourceRanges()) > 0 {
			ranges := make([]interface{}, 0, len(spec.GetExpose().GetSourceRanges()))
			for _, r := range spec.GetExpose().GetSourceRanges() {
				ranges = append(ranges, r)
			}
			activeArm["sourceRanges"] = ranges
		}
		exposeBlock["loadBalancer"] = activeArm
	}
	values["expose"] = exposeBlock

	// --------------------------- admin password ---------------------------
	values["existingSecretAdminPassword"] = locals.AdminSecretName
	values["existingSecretAdminPasswordKey"] = locals.AdminSecretKey

	// ----------------------- inter-component secrets ----------------------
	// All generated by the module into ONE Secret (see auth_secrets.go)
	// — the chart's own fallbacks are either lookup-randAlphaNum
	// (stable, but invisible to state) or PUBLIC documented defaults.
	values["existingSecretSecretKey"] = locals.InternalAuthSecretName

	coreBlock := componentBlock(spec.GetCore(), spec)
	coreBlock["existingSecret"] = locals.InternalAuthSecretName
	coreBlock["existingXsrfSecret"] = locals.InternalAuthSecretName
	values["core"] = coreBlock

	jobserviceBlock := map[string]interface{}{
		"existingSecret": locals.InternalAuthSecretName,
	}
	if js := spec.GetJobservice(); js != nil {
		if js.Replicas != nil {
			jobserviceBlock["replicas"] = int(js.GetReplicas())
		}
		if r := resourcesBlock(js.GetResources()); r != nil {
			jobserviceBlock["resources"] = r
		}
		if js.MaxJobWorkers != nil {
			jobserviceBlock["maxJobWorkers"] = int(js.GetMaxJobWorkers())
		}
	}
	applyScheduling(jobserviceBlock, spec)
	values["jobservice"] = jobserviceBlock

	registryBlock := map[string]interface{}{
		"existingSecret": locals.InternalAuthSecretName,
		"credentials": map[string]interface{}{
			// The username is not secret material; the module-generated
			// PASSWORD pair (REGISTRY_PASSWD/REGISTRY_HTPASSWD) lives in
			// the internal-auth Secret.
			"username":       vars.RegistryCredentialUsername,
			"existingSecret": locals.InternalAuthSecretName,
		},
	}
	if reg := spec.GetRegistry(); reg != nil {
		if reg.Replicas != nil {
			registryBlock["replicas"] = int(reg.GetReplicas())
		}
		if r := resourcesBlock(reg.GetResources()); r != nil {
			// Applied to the registry (distribution) container; the
			// small registryctl sidecar keeps chart defaults — size it
			// via helm_values (registry.controller.resources) if ever
			// needed.
			registryBlock["registry"] = map[string]interface{}{"resources": r}
		}
	}
	applyScheduling(registryBlock, spec)
	values["registry"] = registryBlock

	portalBlock := componentBlock(spec.GetPortal(), spec)
	values["portal"] = portalBlock

	nginxBlock := componentBlock(spec.GetNginx(), spec)
	values["nginx"] = nginxBlock

	// ------------------------------ database ------------------------------
	databaseBlock := map[string]interface{}{}
	if spec.GetDatabase().GetInternal() != nil {
		internal := map[string]interface{}{
			// The chart's ONLY intake for this credential is a value —
			// it rides as a SECRET-marked entry (redacted in preview;
			// the TF twin's random_password reference marks the whole
			// rendered values sensitive).
			"password": gen.InternalDatabasePassword,
		}
		if r := resourcesBlock(spec.GetDatabase().GetInternal().GetResources()); r != nil {
			internal["resources"] = r
		}
		if spec.GetDatabase().GetInternal().GetShmSizeLimit() != "" {
			internal["shmSizeLimit"] = spec.GetDatabase().GetInternal().GetShmSizeLimit()
		}
		applyScheduling(internal, spec)
		databaseBlock["type"] = "internal"
		databaseBlock["internal"] = internal
	} else if ext := spec.GetDatabase().GetExternal(); ext != nil {
		port := "5432"
		if ext.Port != nil {
			port = itoa(int(ext.GetPort()))
		}
		coreDatabase := "registry"
		if ext.GetCoreDatabase() != "" {
			coreDatabase = ext.GetCoreDatabase()
		}
		sslMode := "disable"
		if ext.GetSslMode() != "" {
			sslMode = ext.GetSslMode()
		}
		databaseBlock["type"] = "external"
		databaseBlock["external"] = map[string]interface{}{
			"host":     ext.GetHost().GetValue(),
			"port":     port, // the chart takes the port as a string
			"username": ext.GetUsername(),
			// The chart contract pins the key inside this Secret to
			// `password` — exactly the KubernetesPostgres application
			// Secret's key, so its credential composes as-is.
			"existingSecret": ext.GetPasswordSecretName().GetValue(),
			"coreDatabase":   coreDatabase,
			"sslmode":        sslMode,
		}
	}
	values["database"] = databaseBlock

	// -------------------------------- redis -------------------------------
	redisBlock := map[string]interface{}{}
	if spec.GetCache().GetInternal() != nil {
		internal := map[string]interface{}{}
		if r := resourcesBlock(spec.GetCache().GetInternal().GetResources()); r != nil {
			internal["resources"] = r
		}
		applyScheduling(internal, spec)
		redisBlock["type"] = "internal"
		if len(internal) > 0 {
			redisBlock["internal"] = internal
		}
	} else if ext := spec.GetCache().GetExternal(); ext != nil {
		external := map[string]interface{}{
			"addr": ext.GetAddr().GetValue(),
		}
		if ext.GetSentinelMasterSet() != "" {
			external["sentinelMasterSet"] = ext.GetSentinelMasterSet()
		}
		if ext.GetUsername() != "" {
			external["username"] = ext.GetUsername()
		}
		switch {
		case ext.GetExistingSecretName() != "":
			external["existingSecret"] = ext.GetExistingSecretName()
		case ext.GetPassword() != "":
			// Declared password → materialized by the module into
			// `<name>-redis-auth` under the chart's contract keys; only
			// the NAME renders here.
			external["existingSecret"] = locals.RedisAuthSecretName
		}
		if ext.GetTlsEnabled() {
			external["tlsOptions"] = map[string]interface{}{"enable": true}
		}
		redisBlock["type"] = "external"
		redisBlock["external"] = external
	}
	values["redis"] = redisBlock

	// ---------------------------- persistence -----------------------------
	resourcePolicy := "keep"
	if spec.KeepVolumesOnUninstall != nil && !spec.GetKeepVolumesOnUninstall() {
		resourcePolicy = ""
	}
	pvcBlock := map[string]interface{}{}
	if fs := spec.GetStorage().GetFilesystem(); fs != nil {
		registryPvc := map[string]interface{}{}
		if fs.GetDiskSize() != "" {
			registryPvc["size"] = fs.GetDiskSize()
		}
		if fs.GetStorageClass() != "" {
			registryPvc["storageClass"] = fs.GetStorageClass()
		}
		if fs.GetAccessMode() != "" {
			registryPvc["accessMode"] = fs.GetAccessMode()
		}
		if len(registryPvc) > 0 {
			pvcBlock["registry"] = registryPvc
		}
	}
	if js := spec.GetJobservice(); js != nil && js.GetLogDiskSize() != "" {
		pvcBlock["jobservice"] = map[string]interface{}{
			"jobLog": map[string]interface{}{"size": js.GetLogDiskSize()},
		}
	}
	if internal := spec.GetDatabase().GetInternal(); internal != nil {
		databasePvc := map[string]interface{}{}
		if internal.GetDiskSize() != "" {
			databasePvc["size"] = internal.GetDiskSize()
		}
		if internal.GetStorageClass() != "" {
			databasePvc["storageClass"] = internal.GetStorageClass()
		}
		if len(databasePvc) > 0 {
			pvcBlock["database"] = databasePvc
		}
	}
	if internal := spec.GetCache().GetInternal(); internal != nil {
		redisPvc := map[string]interface{}{}
		if internal.GetDiskSize() != "" {
			redisPvc["size"] = internal.GetDiskSize()
		}
		if internal.GetStorageClass() != "" {
			redisPvc["storageClass"] = internal.GetStorageClass()
		}
		if len(redisPvc) > 0 {
			pvcBlock["redis"] = redisPvc
		}
	}
	if locals.TrivyEnabled && spec.GetTrivy().GetDiskSize() != "" {
		pvcBlock["trivy"] = map[string]interface{}{"size": spec.GetTrivy().GetDiskSize()}
	}

	persistence := map[string]interface{}{
		"enabled":           true,
		"resourcePolicy":    resourcePolicy,
		"imageChartStorage": storageBlock(locals),
	}
	if len(pvcBlock) > 0 {
		persistence["persistentVolumeClaim"] = pvcBlock
	}
	values["persistence"] = persistence

	// -------------------------------- trivy -------------------------------
	trivyBlock := map[string]interface{}{
		"enabled": locals.TrivyEnabled,
	}
	if locals.TrivyEnabled {
		if t := spec.GetTrivy(); t != nil {
			if t.Replicas != nil {
				trivyBlock["replicas"] = int(t.GetReplicas())
			}
			if r := resourcesBlock(t.GetResources()); r != nil {
				trivyBlock["resources"] = r
			}
			if t.GetSkipUpdate() {
				trivyBlock["skipUpdate"] = true
			}
			if t.GetSkipJavaDbUpdate() {
				trivyBlock["skipJavaDBUpdate"] = true
			}
			if t.GetOfflineScan() {
				trivyBlock["offlineScan"] = true
			}
			if len(t.GetDbRepositories()) > 0 {
				trivyBlock["dbRepository"] = stringSliceToInterface(t.GetDbRepositories())
			}
			if len(t.GetJavaDbRepositories()) > 0 {
				trivyBlock["javaDBRepository"] = stringSliceToInterface(t.GetJavaDbRepositories())
			}
			if t.GetGithubToken() != "" {
				// The chart accepts this only as a value (it renders it
				// into its own trivy Secret) — SECRET-wrapped so it is
				// redacted in previews.
				trivyBlock["gitHubToken"] = pulumi.ToSecret(pulumi.String(t.GetGithubToken()))
			}
			if t.GetSeverity() != "" {
				trivyBlock["severity"] = t.GetSeverity()
			}
			if t.GetIgnoreUnfixed() {
				trivyBlock["ignoreUnfixed"] = true
			}
			if t.GetTimeout() != "" {
				trivyBlock["timeout"] = t.GetTimeout()
			}
		}
		applyScheduling(trivyBlock, spec)
	}
	values["trivy"] = trivyBlock

	// ----------------------------- internal TLS ---------------------------
	if it := spec.GetInternalTls(); it != nil && it.GetEnabled() {
		internalTls := map[string]interface{}{
			"enabled":            true,
			"strong_ssl_ciphers": it.GetStrongSslCiphers(),
		}
		if cs := it.GetCertSecrets(); cs != nil {
			internalTls["certSource"] = "secret"
			internalTls["core"] = map[string]interface{}{"secretName": cs.GetCoreSecretName()}
			internalTls["jobservice"] = map[string]interface{}{"secretName": cs.GetJobserviceSecretName()}
			internalTls["registry"] = map[string]interface{}{"secretName": cs.GetRegistrySecretName()}
			internalTls["portal"] = map[string]interface{}{"secretName": cs.GetPortalSecretName()}
			if cs.GetTrivySecretName() != "" {
				internalTls["trivy"] = map[string]interface{}{"secretName": cs.GetTrivySecretName()}
			}
		} else {
			// Chart-generated internal CA — regenerated on EVERY apply
			// (rolls every component); documented as labs-only on the
			// spec field.
			internalTls["certSource"] = "auto"
		}
		values["internalTLS"] = internalTls
	}

	// ------------------------------- metrics ------------------------------
	if m := spec.GetMetrics(); m != nil && m.GetEnabled() {
		metrics := map[string]interface{}{"enabled": true}
		if m.GetServiceMonitorEnabled() {
			serviceMonitor := map[string]interface{}{"enabled": true}
			if m.GetServiceMonitorInterval() != "" {
				serviceMonitor["interval"] = m.GetServiceMonitorInterval()
			}
			if len(m.GetServiceMonitorLabels()) > 0 {
				serviceMonitor["additionalLabels"] = stringMapToInterface(m.GetServiceMonitorLabels())
			}
			metrics["serviceMonitor"] = serviceMonitor
		}
		values["metrics"] = metrics

		exporterBlock := map[string]interface{}{}
		applyScheduling(exporterBlock, spec)
		if len(exporterBlock) > 0 {
			values["exporter"] = exporterBlock
		}
	}

	// ----------------------------- cache layer ----------------------------
	if c := spec.GetCacheLayer(); c != nil && c.GetEnabled() {
		cacheBlock := map[string]interface{}{"enabled": true}
		if c.ExpireHours != nil {
			cacheBlock["expireHours"] = int(c.GetExpireHours())
		}
		values["cache"] = cacheBlock
	}

	// ---------------------------- outbound proxy --------------------------
	if p := spec.GetOutboundProxy(); p != nil && (p.GetHttpProxy() != "" || p.GetHttpsProxy() != "") {
		proxyBlock := map[string]interface{}{}
		if p.GetHttpProxy() != "" {
			proxyBlock["httpProxy"] = p.GetHttpProxy()
		}
		if p.GetHttpsProxy() != "" {
			proxyBlock["httpsProxy"] = p.GetHttpsProxy()
		}
		if p.GetNoProxy() != "" {
			proxyBlock["noProxy"] = p.GetNoProxy()
		}
		values["proxy"] = proxyBlock
	}

	// ------------------------------- misc ---------------------------------
	if len(spec.GetImagePullSecrets()) > 0 {
		pullSecrets := make([]interface{}, 0, len(spec.GetImagePullSecrets()))
		for _, s := range spec.GetImagePullSecrets() {
			pullSecrets = append(pullSecrets, map[string]interface{}{"name": s})
		}
		values["imagePullSecrets"] = pullSecrets
	}
	if spec.GetUpdateStrategy() != "" && spec.GetUpdateStrategy() != "RollingUpdate" {
		values["updateStrategy"] = map[string]interface{}{"type": spec.GetUpdateStrategy()}
	}
	if spec.GetCaBundleSecretName() != "" {
		values["caBundleSecretName"] = spec.GetCaBundleSecretName()
	}

	// --------------------------- air-gap mirror ---------------------------
	// The chart pins every component image to
	// docker.io/goharbor/<component>:v<appVersion>; the mirror replaces
	// the docker.io host, keeping the goharbor/* paths and chart-default
	// tags (the tag keys stay unset — chart defaults apply).
	if mirror := spec.GetImageRegistry(); mirror != "" {
		applyImageMirror(values, mirror, locals)
	}

	// ------------------------- helm_values escape --------------------------
	// Merged LAST with Helm -f semantics; fullnameOverride and the
	// front-door Service name are re-pinned after the merge — resource
	// naming is the module's identity contract.
	if spec.GetHelmValues() != "" {
		var overrides map[string]interface{}
		if err := yaml.Unmarshal([]byte(spec.GetHelmValues()), &overrides); err != nil {
			return nil, errors.Wrap(err, "helm_values is not valid YAML")
		}
		values = mergeMaps(values, overrides)
		values["fullnameOverride"] = locals.ReleaseName
		if expose, ok := values["expose"].(map[string]interface{}); ok {
			if arm, ok := expose[locals.ExposeType].(map[string]interface{}); ok {
				arm["name"] = locals.ReleaseName
			}
		}
	}

	return values, nil
}

// componentBlock renders the shared component sizing shape (replicas +
// resources + fanned-out scheduling).
func componentBlock(c *kubernetesharborv1alpha1.KubernetesHarborComponent, spec *kubernetesharborv1alpha1.KubernetesHarborSpec) map[string]interface{} {
	block := map[string]interface{}{}
	if c != nil {
		if c.Replicas != nil {
			block["replicas"] = int(c.GetReplicas())
		}
		if r := resourcesBlock(c.GetResources()); r != nil {
			block["resources"] = r
		}
	}
	applyScheduling(block, spec)
	return block
}

// applyScheduling fans the spec-level scheduling constraints onto a
// component block — split placement would separate components that
// share volumes and fail over together (per-component placement rides
// helm_values).
func applyScheduling(block map[string]interface{}, spec *kubernetesharborv1alpha1.KubernetesHarborSpec) {
	sched := spec.GetScheduling()
	if sched == nil {
		return
	}
	if len(sched.GetNodeSelector()) > 0 {
		block["nodeSelector"] = stringMapToInterface(sched.GetNodeSelector())
	}
	if len(sched.GetTolerations()) > 0 {
		block["tolerations"] = tolerationsSlice(sched.GetTolerations())
	}
}

// storageBlock renders persistence.imageChartStorage from the storage
// oneof. Credentials travel by Secret name (module-owned or
// user-provided); the keyless arms render no credential keys at all.
func storageBlock(locals *Locals) map[string]interface{} {
	spec := locals.Spec
	storage := map[string]interface{}{}

	switch {
	case spec.GetStorage().GetFilesystem() != nil:
		storage["type"] = "filesystem"
		storage["filesystem"] = map[string]interface{}{
			"rootdirectory": "/storage",
		}

	case spec.GetStorage().GetS3() != nil:
		s3 := spec.GetStorage().GetS3()
		s3Block := map[string]interface{}{
			"bucket": s3.GetBucket(),
			"region": s3.GetRegion(),
		}
		if s3.GetEndpoint().GetValue() != "" {
			s3Block["regionendpoint"] = s3.GetEndpoint().GetValue()
		}
		switch {
		case s3.GetCredentials().GetExistingSecretName() != "":
			s3Block["existingSecret"] = s3.GetCredentials().GetExistingSecretName()
		case s3.GetCredentials().GetAccessKey() != "":
			s3Block["existingSecret"] = locals.StorageAuthSecretName
		}
		if s3.GetEncrypt() {
			s3Block["encrypt"] = true
		}
		secure := true
		if s3.Secure != nil {
			secure = s3.GetSecure()
		}
		s3Block["secure"] = secure
		if s3.GetSkipVerify() {
			s3Block["skipverify"] = true
		}
		if s3.GetRootDirectory() != "" {
			s3Block["rootdirectory"] = s3.GetRootDirectory()
		}
		if s3.GetStorageClass() != "" {
			s3Block["storageclass"] = s3.GetStorageClass()
		}
		storage["type"] = "s3"
		storage["s3"] = s3Block
		if s3.GetDisableRedirect() {
			storage["disableredirect"] = true
		}

	case spec.GetStorage().GetGcs() != nil:
		gcs := spec.GetStorage().GetGcs()
		gcsBlock := map[string]interface{}{
			"bucket": gcs.GetBucket(),
		}
		switch {
		case gcs.GetUseWorkloadIdentity():
			gcsBlock["useWorkloadIdentity"] = true
		case gcs.GetExistingSecretName() != "":
			gcsBlock["existingSecret"] = gcs.GetExistingSecretName()
		case gcs.GetKeyData() != "":
			gcsBlock["existingSecret"] = locals.StorageAuthSecretName
		}
		if gcs.GetRootDirectory() != "" {
			gcsBlock["rootdirectory"] = gcs.GetRootDirectory()
		}
		if gcs.ChunkSize != nil {
			gcsBlock["chunksize"] = itoa(int(gcs.GetChunkSize())) // the chart takes it as a string
		}
		storage["type"] = "gcs"
		storage["gcs"] = gcsBlock

	case spec.GetStorage().GetAzure() != nil:
		azure := spec.GetStorage().GetAzure()
		azureBlock := map[string]interface{}{
			"accountname": azure.GetAccountName(),
			"container":   azure.GetContainer(),
		}
		switch {
		case azure.GetExistingSecretName() != "":
			azureBlock["existingSecret"] = azure.GetExistingSecretName()
		case azure.GetAccountKey() != "":
			azureBlock["existingSecret"] = locals.StorageAuthSecretName
		}
		if azure.GetRealm() != "" && azure.GetRealm() != "core.windows.net" {
			azureBlock["realm"] = azure.GetRealm()
		}
		storage["type"] = "azure"
		storage["azure"] = azureBlock
	}

	return storage
}

// applyImageMirror rewrites the registry host of every component image
// onto the declared mirror (repository-only overrides — chart-default
// tags stay in force).
func applyImageMirror(values map[string]interface{}, mirror string, locals *Locals) {
	setImage := func(block map[string]interface{}, image string) {
		block["image"] = map[string]interface{}{
			"repository": mirror + "/goharbor/" + image,
		}
	}
	ensure := func(key string) map[string]interface{} {
		if child, ok := values[key].(map[string]interface{}); ok {
			return child
		}
		child := map[string]interface{}{}
		values[key] = child
		return child
	}

	setImage(ensure("nginx"), "nginx-photon")
	setImage(ensure("portal"), "harbor-portal")
	setImage(ensure("core"), "harbor-core")
	setImage(ensure("jobservice"), "harbor-jobservice")

	registryBlock := ensure("registry")
	registryInner, ok := registryBlock["registry"].(map[string]interface{})
	if !ok {
		registryInner = map[string]interface{}{}
		registryBlock["registry"] = registryInner
	}
	setImage(registryInner, "registry-photon")
	controllerInner, ok := registryBlock["controller"].(map[string]interface{})
	if !ok {
		controllerInner = map[string]interface{}{}
		registryBlock["controller"] = controllerInner
	}
	setImage(controllerInner, "harbor-registryctl")

	if locals.TrivyEnabled {
		setImage(ensure("trivy"), "trivy-adapter-photon")
	}
	if locals.Spec.GetMetrics().GetEnabled() {
		setImage(ensure("exporter"), "harbor-exporter")
	}
	if locals.InternalDatabase {
		databaseBlock := ensure("database")
		internalInner, ok := databaseBlock["internal"].(map[string]interface{})
		if !ok {
			internalInner = map[string]interface{}{}
			databaseBlock["internal"] = internalInner
		}
		setImage(internalInner, "harbor-db")
	}
	if locals.InternalRedis {
		redisBlock := ensure("redis")
		internalInner, ok := redisBlock["internal"].(map[string]interface{})
		if !ok {
			internalInner = map[string]interface{}{}
			redisBlock["internal"] = internalInner
		}
		setImage(internalInner, "redis-photon")
	}
}

func stringSliceToInterface(in []string) []interface{} {
	out := make([]interface{}, 0, len(in))
	for _, v := range in {
		out = append(out, v)
	}
	return out
}

