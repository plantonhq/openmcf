package module

import (
	"fmt"

	"github.com/pkg/errors"
	kubernetesprovider "github.com/plantonhq/planton/apis/dev/planton/provider/kubernetes"
	kubernetesargocdv1alpha1 "github.com/plantonhq/planton/apis/dev/planton/provider/kubernetes/kubernetesargocd/v1alpha1"
	"sigs.k8s.io/yaml"
)

// buildHelmValues renders the typed spec into the chart's values map, then
// merges the spec's helm_values escape hatch over it with Helm `-f`
// semantics (maps deep-merge with the later document winning, lists
// replace).
//
// SECRET DISCIPLINE (load-bearing): nothing rendered here carries
// credential material. The initial admin password is generated by Argo CD
// ITSELF at first start; the OIDC client secret rides Argo CD's own
// `$<secret-name>:<key>` runtime indirection against a Secret labeled
// app.kubernetes.io/part-of: argocd; external-Redis credentials ride the
// chart's existingSecret contract; private-repo credentials are labeled
// Secrets composed OUTSIDE this module entirely.
//
// PARITY: the Terraform module reaches the same result natively — its
// helm_release passes values = [yamlencode(typed values), helm_values] and
// the provider merges the documents in exactly this order. Keep every typed
// mapping below in lockstep with the Terraform module's locals.
func buildHelmValues(locals *Locals) (map[string]interface{}, error) {
	spec := locals.Spec
	values := map[string]interface{}{}

	// fullnameOverride pins every child name (`<name>-server`,
	// `<name>-application-controller`, ...) to the resource name; the
	// exported outputs are built from that contract.
	values["fullnameOverride"] = locals.ReleaseName

	// ---- CRD lifecycle -----------------------------------------------------
	if crds := spec.GetCrds(); crds != nil {
		install := true
		if crds.Install != nil {
			install = crds.GetInstall()
		}
		keep := true
		if crds.Keep != nil {
			keep = crds.GetKeep()
		}
		values["crds"] = map[string]interface{}{
			"install": install,
			"keep":    keep,
		}
	}

	// ---- global block (domain + image + scheduling) --------------------------
	// ONE Argo CD image serves every component; the chart's global.image
	// takes the repository COMBINED (registry included) — no split needed
	// (unlike split-image charts; verified against the chart's global
	// section).
	global := map[string]interface{}{}
	if spec.GetDomain() != "" {
		global["domain"] = spec.GetDomain()
	}
	if img := spec.GetImage(); img != nil {
		image := map[string]interface{}{}
		if img.GetRepository() != "" {
			image["repository"] = img.GetRepository()
		}
		if img.GetTag() != "" {
			image["tag"] = img.GetTag()
		}
		if len(image) > 0 {
			global["image"] = image
		}
		if img.GetPullSecretName() != "" {
			global["imagePullSecrets"] = []interface{}{
				map[string]interface{}{"name": img.GetPullSecretName()},
			}
		}
	}
	if sched := spec.GetScheduling(); sched != nil {
		if len(sched.GetNodeSelector()) > 0 {
			global["nodeSelector"] = stringMapToInterface(sched.GetNodeSelector())
		}
		if len(sched.GetTolerations()) > 0 {
			global["tolerations"] = tolerationsSlice(sched.GetTolerations())
		}
		if sched.GetPriorityClassName() != "" {
			global["priorityClassName"] = sched.GetPriorityClassName()
		}
	}
	if len(global) > 0 {
		values["global"] = global
	}

	// ---- configs (argocd-cm / params / rbac / repositories) -------------------
	configs := map[string]interface{}{}

	cm := map[string]interface{}{}
	if !locals.AdminEnabled {
		cm["admin.enabled"] = false
	}
	if spec.GetExecEnabled() {
		cm["exec.enabled"] = true
	}
	if spec.GetReconciliationTimeout() != "" {
		cm["timeout.reconciliation"] = spec.GetReconciliationTimeout()
	}
	if sso := spec.GetSso(); sso != nil {
		if oidc := sso.GetOidc(); oidc != nil {
			oidcDoc := map[string]interface{}{
				"name":     oidc.GetName(),
				"issuer":   oidc.GetIssuer(),
				"clientID": oidc.GetClientId(),
			}
			if ref := oidc.GetClientSecretSecret(); ref != nil {
				// Argo CD resolves `$<secret-name>:<key>` at runtime from
				// a Secret labeled app.kubernetes.io/part-of: argocd — the
				// client secret never lands in the ConfigMap text.
				oidcDoc["clientSecret"] = fmt.Sprintf("$%s:%s", ref.GetName(), ref.GetKey())
			} else {
				// A public client authenticates the authorization-code
				// flow with PKCE instead of a client secret.
				oidcDoc["enablePKCEAuthentication"] = true
			}
			oidcYaml, err := yaml.Marshal(oidcDoc)
			if err != nil {
				return nil, errors.Wrap(err, "failed to render oidc.config document")
			}
			cm["oidc.config"] = string(oidcYaml)
		}
		if sso.GetDexConfig() != "" {
			cm["dex.config"] = sso.GetDexConfig()
		}
	}
	if len(cm) > 0 {
		configs["cm"] = cm
	}

	if spec.GetServer().GetInsecure() {
		configs["params"] = map[string]interface{}{"server.insecure": true}
	}

	if rbac := spec.GetRbac(); rbac != nil {
		rbacValues := map[string]interface{}{}
		if rbac.GetPolicyDefault() != "" {
			rbacValues["policy.default"] = rbac.GetPolicyDefault()
		}
		if rbac.GetPolicyCsv() != "" {
			rbacValues["policy.csv"] = rbac.GetPolicyCsv()
		}
		if rbac.GetScopes() != "" {
			rbacValues["scopes"] = rbac.GetScopes()
		}
		if len(rbacValues) > 0 {
			configs["rbac"] = rbacValues
		}
	}

	// Public repositories only — each entry renders one chart-managed
	// repository Secret carrying url + type; credentialed repos are
	// composed labeled Secrets outside this module (the spec's teaching).
	if len(spec.GetRepositories()) > 0 {
		repositories := map[string]interface{}{}
		for _, r := range spec.GetRepositories() {
			repoType := r.GetType()
			if repoType == "" {
				repoType = "git"
			}
			repositories[r.GetName()] = map[string]interface{}{
				"url":  r.GetUrl(),
				"type": repoType,
			}
		}
		configs["repositories"] = repositories
	}

	if len(configs) > 0 {
		values["configs"] = configs
	}

	// ---- per-component blocks -------------------------------------------------
	// Every component with a serviceMonitor toggle at the pin (controller,
	// server, repo server, applicationSet, notifications, dex) gets the
	// same metrics pair from the single spec toggle — partial monitoring
	// of a control plane is a trap. The commit server exposes NO
	// serviceMonitor toggle at chart 10.2.1 (metrics service only), and
	// the redis exporter is a separate opt-in sidecar surface — both stay
	// chart-default (reachable via helm_values).
	metricsBlock := map[string]interface{}{}
	if spec.GetServiceMonitorsEnabled() {
		metricsBlock["metrics"] = map[string]interface{}{
			"enabled":        true,
			"serviceMonitor": map[string]interface{}{"enabled": true},
		}
	}

	// The application controller ({replicas, resources}).
	controller := map[string]interface{}{}
	if c := spec.GetController(); c != nil {
		if c.Replicas != nil {
			controller["replicas"] = int(c.GetReplicas())
		}
		if resources := resourcesBlock(c.GetResources()); resources != nil {
			controller["resources"] = resources
		}
	}
	mergeInto(controller, metricsBlock)
	if len(controller) > 0 {
		values["controller"] = controller
	}

	// The server: replicas yield to the HPA when autoscaling is enabled
	// (the HPA owns the count — rendering both would fight it).
	server := map[string]interface{}{}
	if s := spec.GetServer(); s != nil {
		if autoscaling := autoscalingBlock(s.GetAutoscaling()); autoscaling != nil {
			server["autoscaling"] = autoscaling
		} else if s.Replicas != nil {
			server["replicas"] = int(s.GetReplicas())
		}
		if resources := resourcesBlock(s.GetResources()); resources != nil {
			server["resources"] = resources
		}
	}
	mergeInto(server, metricsBlock)
	if len(server) > 0 {
		values["server"] = server
	}

	// The repo server (same autoscaling-owns-replicas contract).
	repoServer := map[string]interface{}{}
	if rs := spec.GetRepoServer(); rs != nil {
		if autoscaling := autoscalingBlock(rs.GetAutoscaling()); autoscaling != nil {
			repoServer["autoscaling"] = autoscaling
		} else if rs.Replicas != nil {
			repoServer["replicas"] = int(rs.GetReplicas())
		}
		if resources := resourcesBlock(rs.GetResources()); resources != nil {
			repoServer["resources"] = resources
		}
	}
	mergeInto(repoServer, metricsBlock)
	if len(repoServer) > 0 {
		values["repoServer"] = repoServer
	}

	// The ApplicationSet controller ({replicas, resources}).
	applicationSet := map[string]interface{}{}
	if as := spec.GetApplicationSet(); as != nil {
		if as.Replicas != nil {
			applicationSet["replicas"] = int(as.GetReplicas())
		}
		if resources := resourcesBlock(as.GetResources()); resources != nil {
			applicationSet["resources"] = resources
		}
	}
	mergeInto(applicationSet, metricsBlock)
	if len(applicationSet) > 0 {
		values["applicationSet"] = applicationSet
	}

	// The toggleable components ({enabled, resources}); notifications and
	// dex also carry the metrics pair (the commit server has no
	// serviceMonitor toggle at the pin).
	if block := toggleableBlock(spec.GetNotifications()); true {
		mergeInto(block, metricsBlock)
		if len(block) > 0 {
			values["notifications"] = block
		}
	}
	if block := toggleableBlock(spec.GetDex()); true {
		mergeInto(block, metricsBlock)
		if len(block) > 0 {
			values["dex"] = block
		}
	}
	if block := toggleableBlock(spec.GetCommitServer()); len(block) > 0 {
		values["commitServer"] = block
	}

	// ---- the redis arm ----------------------------------------------------------
	// The chart's own switch logic (verified in its redis.server helper):
	// bundled redis serves when redis.enabled && !redis-ha.enabled; the
	// HA subchart serves when redis-ha.enabled (haproxy fronting it); an
	// external endpoint serves only when the bundled arm is DISABLED and
	// externalRedis.host is set. Exactly one of the three states renders.
	if redis := spec.GetRedis(); redis != nil {
		switch arm := redis.GetArm().(type) {
		case *kubernetesargocdv1alpha1.KubernetesArgocdRedis_Bundled:
			if resources := resourcesBlock(arm.Bundled.GetResources()); resources != nil {
				values["redis"] = map[string]interface{}{"resources": resources}
			}
		case *kubernetesargocdv1alpha1.KubernetesArgocdRedis_Ha:
			ha := map[string]interface{}{"enabled": true}
			if arm.Ha.Replicas != nil {
				ha["replicas"] = int(arm.Ha.GetReplicas())
			}
			values["redis-ha"] = ha
		case *kubernetesargocdv1alpha1.KubernetesArgocdRedis_External:
			values["redis"] = map[string]interface{}{"enabled": false}
			port := 6379
			if arm.External.Port != nil {
				port = int(arm.External.GetPort())
			}
			external := map[string]interface{}{
				"host": arm.External.GetHost().GetValue(),
				"port": port,
			}
			if arm.External.GetCredentialsSecretName() != "" {
				external["existingSecret"] = arm.External.GetCredentialsSecretName()
			}
			values["externalRedis"] = external
		}
	}

	// ---- escape hatch (merged LAST, helm -f semantics) ----------------------------
	if spec.GetHelmValues() != "" {
		overrides := map[string]interface{}{}
		if err := yaml.Unmarshal([]byte(spec.GetHelmValues()), &overrides); err != nil {
			return nil, errors.Wrap(err, "failed to parse helm_values as a YAML document")
		}
		values = mergeMaps(values, overrides)
	}

	// fullnameOverride re-pinned AFTER the merge — the one deliberate
	// exception to the escape hatch's last-word contract (twin of the
	// Terraform module's third values document). Every child name — and
	// the exported outputs built from them — derive from the fullname;
	// letting an override move it would break every output.
	values["fullnameOverride"] = locals.ReleaseName

	return values, nil
}

// resourcesBlock renders a ContainerResources into the chart's resources
// shape (nil when nothing is declared).
func resourcesBlock(r *kubernetesprovider.ContainerResources) map[string]interface{} {
	if r == nil {
		return nil
	}
	resources := map[string]interface{}{}
	if q := r.GetRequests(); q != nil && (q.GetCpu() != "" || q.GetMemory() != "") {
		requests := map[string]interface{}{}
		if q.GetCpu() != "" {
			requests["cpu"] = q.GetCpu()
		}
		if q.GetMemory() != "" {
			requests["memory"] = q.GetMemory()
		}
		resources["requests"] = requests
	}
	if l := r.GetLimits(); l != nil && (l.GetCpu() != "" || l.GetMemory() != "") {
		limits := map[string]interface{}{}
		if l.GetCpu() != "" {
			limits["cpu"] = l.GetCpu()
		}
		if l.GetMemory() != "" {
			limits["memory"] = l.GetMemory()
		}
		resources["limits"] = limits
	}
	if len(resources) == 0 {
		return nil
	}
	return resources
}
